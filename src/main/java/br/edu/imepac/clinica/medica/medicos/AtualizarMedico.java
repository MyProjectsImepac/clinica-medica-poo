    private void validarDados() {
        String nome = nomeText.getText();
        String crm = crmText.getText();

        Especialidade especialidade = (Especialidade) especialidadeJcombobox.getSelectedItem();

        if (nome.isEmpty() || crm.isEmpty() || especialidade == null) {
            JOptionPane.showMessageDialog(null, "Todos os campos devem ser preenchidos!");
            return;
        }

        try {
            Medico medico = new Medico();
            medico.setNome(nome);
            medico.setCrm(crm);
            medico.setEspecialidade(especialidade);

            medicoDao.salvar(medico);

            JOptionPane.showMessageDialog(null, "Médico cadastrado com sucesso!");
            limparForm();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Erro ao cadastrar médico: " + e.getMessage());
        }
    }

    private void limparForm() {
        nomeText.setText("");
        crmText.setText("");
        especialidadeJcombobox.setSelectedIndex(0);
    }

