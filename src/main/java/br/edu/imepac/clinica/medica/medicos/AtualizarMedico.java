    private void carregarDadosDeEdicao(int id) {
        try {
            Medico medico = medicoDao.buscarPorId(id);
            if (medico != null) {
                nomeText.setText(medico.getNome());
                crmText.setText(medico.getCrm());
                Especialidade especialidade = especialidadeDao.buscarPorId(medico.getEspecialidadeId());
                especialidadeJcombobox.setSelectedItem(especialidade);
            } else {
                JOptionPane.showMessageDialog(null, "Médico não encontrado!");
                dispose();
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Erro ao carregar dados do médico: " + e.getMessage());
            dispose();
        }
    }

    private void inicializarEpecialidadeDao() {
        try {
            this.especialidadeDao = new EspecialidadeDao();
        } catch (Exception exception) {
            JOptionPane.showMessageDialog(null, "Erro ao conectar ao banco de dados - especialidades!");
            dispose();
        }
    }

    private void inicializarMedicoDao() {
        try {
            this.medicoDao = new MedicoDao();
        } catch (Exception exception) {
            JOptionPane.showMessageDialog(null, "Erro ao inicializar ao banco de dados - médico!");
            dispose();
        }
    }

    private void carregarEspecialidades() {
        try {
            List<Especialidade> especialidadesList = especialidadeDao.listarTodas();
            if (especialidadesList.isEmpty()) {
                JOptionPane.showMessageDialog(null, "Nenhuma especialidade cadastrada! Cadastre uma especialidade antes de cadastrar um médico.");
                dispose();
                return;
            }
            especialidadesList.forEach(especialidade -> {
                this.especialidadeJcombobox.addItem(especialidade);
            });
        } catch (Exception exception) {
            JOptionPane.showMessageDialog(null, "Erro ao buscar especialidades!");
            dispose();
        }
    }

