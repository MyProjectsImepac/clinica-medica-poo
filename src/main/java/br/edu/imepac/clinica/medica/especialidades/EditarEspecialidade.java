    private void carregarDadosDeEdicao(int id) {
        try {
            Especialidade especialidade = especialidadeDao.buscarPorId(id);
            nomeText.setText(especialidade.getNome());
        } catch (Exception exception) {
            JOptionPane.showMessageDialog(null, "Erro ao buscar dados no banco de dados!");
            dispose();
        }
    }

