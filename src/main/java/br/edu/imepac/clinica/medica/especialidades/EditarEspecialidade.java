    private void salvarEspecialidadeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_salvarEspecialidadeActionPerformed
        boolean isValid = validarDadosObrigatorios();
        if (isValid == true) {
            Especialidade especialidade = new Especialidade();
            especialidade.setNome(nomeText.getText());

            try {
                EspecialidadeDao especialidadeDao = new EspecialidadeDao();
                especialidadeDao.atualizar(especialidade);
            } catch (Exception exception) {
                JOptionPane.showMessageDialog(
                        this,
                        "Banco de dados indisponível!");
            }
            JOptionPane.showMessageDialog(
                    this,
                    "Especialidade atualizada com sucesso!");
            limparForm();
        }
    }//GEN-LAST:event_salvarEspecialidadeActionPerformed

    private boolean validarDadosObrigatorios() {
        if (nomeText.getText().isBlank()) {
            JOptionPane.showMessageDialog(
                    this,
                    "O campo nome é obrigatório!"
            );
            return false;
        }
        return true;
    }

    private void limparForm() {
        nomeText.setText("");
        nomeText.requestFocusInWindow();
    }

